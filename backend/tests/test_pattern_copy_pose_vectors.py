"""`assembly.pattern_copy_pose` against the committed golden vectors (`tests/data/pattern_copy_pose_vectors.json`).

The fixture is generated BY the backend (`tools/motion_vectors/pattern_copy_pose_vectors.py`, which `--check`s that its two committed
copies agree) and read by the other two implementations: the Flutter client's `patternCopyPose` (client/test/pattern_copy_pose_test.dart,
its own copy under client/test/fixtures/) and VR's GDScript mirror (tests/pattern_copy_pose.gd, tests/fixtures/). This test writes nothing:
it fails when the backend's maths drifts from the committed numbers (regenerate, and the other two tests then check their ports).
Also: `pattern_step` (what `pattern_copy_pose` and a constraint model's follower side share) reproduces `pattern_copy_pose` as the
documented `(Rs R, Rs t + ts)` / `(R, Rs t + ts)`."""

import json
from pathlib import Path

import numpy as np

from app.document.assembly import _live_pattern_indices, pattern_copy_pose, pattern_step
from app.document.constraint_model import rigid_to_pose
from app.document.models import ComponentPattern, ComponentPatternAxis, ComponentPatternType, RigidTransform

DATA = json.loads((Path(__file__).resolve().parent / "data" / "pattern_copy_pose_vectors.json").read_text())


def _pattern(j) -> ComponentPattern:
    axis = j["axis"]
    return ComponentPattern(
        id="p", source_occurrence_ids=["src"], pattern_type=ComponentPatternType(j["pattern_type"]), direction=tuple(j["direction"]), count=j["count"],
        spacing=j["spacing"], reverse=j["reverse"], direction_2=tuple(j["direction_2"]), count_2=j["count_2"], spacing_2=j["spacing_2"], reverse_2=j["reverse_2"],
        axis=None if axis is None else ComponentPatternAxis(origin=tuple(axis["origin"]), direction=tuple(axis["direction"])),
        count_angular=j["count_angular"], angle_total=j["angle_total"], reverse_angular=j["reverse_angular"], skip_indices=list(j["skip_indices"]),
        orient_with_rotation=j["orient_with_rotation"],
    )


def _source(j) -> RigidTransform:
    return RigidTransform(translation=tuple(j["translation"]), rotation_axis=tuple(j["rotation_axis"]), rotation_angle_degrees=j["rotation_angle_degrees"])


def test_the_backend_reproduces_the_golden_pattern_copy_poses():
    assert len(DATA["cases"]) >= 40
    tol = DATA["tolerance"]
    for case in DATA["cases"]:
        pattern, source = _pattern(case["pattern"]), _source(case["source"])
        assert _live_pattern_indices(pattern) == case["live_indices"], case["id"]
        for exp in case["expected"]:
            r, t = rigid_to_pose(pattern_copy_pose(pattern, source, exp["index"]))
            assert np.max(np.abs(t - np.array(exp["translation"]))) < tol, (case["id"], exp["index"])
            assert np.max(np.abs(r.reshape(9) - np.array(exp["rotation"]))) < tol, (case["id"], exp["index"])


def test_the_fixture_covers_every_pattern_kind_and_option():
    patterns = [c["pattern"] for c in DATA["cases"]]
    assert any(p["pattern_type"] == "linear" and p["count_2"] == 1 for p in patterns)
    assert any(p["pattern_type"] == "linear" and p["count_2"] > 1 for p in patterns)
    assert any(p["reverse"] for p in patterns) and any(p["reverse_2"] for p in patterns) and any(p["reverse_angular"] for p in patterns)
    assert any(p["pattern_type"] == "circular" and p["orient_with_rotation"] for p in patterns)
    assert any(p["pattern_type"] == "circular" and not p["orient_with_rotation"] for p in patterns)
    assert any(p["skip_indices"] for p in patterns)


def test_pattern_step_is_what_pattern_copy_pose_composes():
    for case in DATA["cases"]:
        pattern, source = _pattern(case["pattern"]), _source(case["source"])
        for index in case["live_indices"]:
            step, keep = pattern_step(pattern, index)
            rs, ts = rigid_to_pose(step)
            r, t = rigid_to_pose(source)
            expected_r = r if keep else rs @ r
            expected_t = rs @ t + ts
            got_r, got_t = rigid_to_pose(pattern_copy_pose(pattern, source, index))
            assert np.allclose(got_r, expected_r, atol=1e-9) and np.allclose(got_t, expected_t, atol=1e-9), (case["id"], index)
            assert keep is (pattern.pattern_type == ComponentPatternType.CIRCULAR and not pattern.orient_with_rotation)
