# Spherical involute primitives
# ---------------------------------------------------------------------------


def spherical_involute_point(
    base_cone_half_angle: float, roll_angle: float, sphere_radius: float = 1.0
) -> tuple[float, float, float]:
    """One point on the spherical involute generated by rolling a great
    circle, without slipping, on the base circle of angular radius
    `base_cone_half_angle` (`gamma_b`) - the spherical analogue of
    `gear_math.involute_point`'s planar `x = r_b(cos t + t sin t)`, `y =
    r_b(sin t - t cos t)`.

    `roll_angle` (`theta`) parametrizes the *base circle's own* azimuth of
    the current point of tangency `B(theta) = (sin(gamma_b) cos(theta),
    sin(gamma_b) sin(theta), cos(gamma_b))` (a unit vector; a great circle
    of constant colatitude `gamma_b` around the +Z axis) - not the
    involute point's own azimuth, which lags behind it as the curve
    unrolls (see `spherical_involute_azimuth_at_colatitude`). The tangent
    direction to the base circle at `B(theta)` is the purely azimuthal
    unit vector `Tang(theta) = (sin(theta), -cos(theta), 0)` - the
    *decreasing*-theta direction, matching `gear_math.involute_point`'s
    own handedness (an earlier draft of this function used the opposite,
    increasing-theta sign; caught by cross-checking the flat-cone/small-
    angle instantiation of this same construction against
    `gear_math.involute_point`'s already-trusted formula bit-for-bit, and
    independently against a from-scratch rigid-body rolling simulation -
    see `10-bevel-gear.md`'s spike findings for the full story, since the
    wrong sign passed several weaker self-consistency checks and only
    this cross-check caught it). The unique great circle through
    `B(theta)` with that initial tangent is `G(s) = B(theta) cos(s) +
    Tang(theta) sin(s)`.

    Rolling without slipping ties the two arc lengths together exactly as
    the planar construction ties string length to base-circle arc: by the
    time the tangency point has swept to azimuth `theta`, it has travelled
    arc length `sin(gamma_b) * theta` along the base circle (arc length on
    a unit-sphere circle of colatitude `gamma_b` is radius `sin(gamma_b)`
    times swept angle) - the marked point, having started *at* the
    tangency point when `theta = 0` (the involute's own start, on the base
    circle itself - `roll_angle = 0` gives exactly `B(0)`, mirroring
    `involute_point(base_radius, 0) == (base_radius, 0)`), now sits that
    same arc length further along the *current* tangent great circle,
    i.e. at `G(u)` with `u = sin(gamma_b) * theta`:

    `Involute(theta) = B(theta) cos(u) + Tang(theta) sin(u)`, `u =
    sin(gamma_b) * theta`.

    This lies exactly on the unit sphere for any `theta`
    (`|B cos(u) + Tang sin(u)|^2 = cos^2(u) + sin^2(u) = 1` since `B` and
    `Tang` are orthonormal by construction) - checked directly in
    `test_bevel_math.py` as a basic sanity property, then scaled by
    `sphere_radius` (the cone distance a real flank is sampled at) since
    the base cone's own half-angle `gamma_b` is scale-invariant - the same
    spherical involute shape appears on every sphere concentric with the
    apex, just scaled, which is exactly why a single `(gamma_b, theta)` ->
    point function suffices for both the outer and inner cone curves
    `docs/gear-design/10-bevel-gear.md`'s OCCT construction needs (call
    twice, once per `sphere_radius`)."""
    if not (0 < base_cone_half_angle < math.pi / 2):
        raise GearGeometryError(f"base_cone_half_angle must be in (0, pi/2), got {base_cone_half_angle!r}")
    gamma_b = base_cone_half_angle
    theta = roll_angle
    u = math.sin(gamma_b) * theta
    cos_u, sin_u = math.cos(u), math.sin(u)
    cos_t, sin_t = math.cos(theta), math.sin(theta)
    sin_gb = math.sin(gamma_b)
    x = sphere_radius * (sin_gb * cos_t * cos_u + sin_t * sin_u)
    y = sphere_radius * (sin_gb * sin_t * cos_u - cos_t * sin_u)
    z = sphere_radius * math.cos(gamma_b) * cos_u
    return (x, y, z)


def spherical_involute_colatitude(base_cone_half_angle: float, roll_angle: float) -> float:
    """The colatitude (angle from the cone axis, radians - the spherical
    analogue of `gear_math`'s planar radius `r(t) = r_b sqrt(1+t^2)`) of
    `spherical_involute_point` at `roll_angle`, without needing to build
    the full 3D point first: `cos(colatitude) = cos(gamma_b) *
    cos(sin(gamma_b) * roll_angle)`, read directly off
    `spherical_involute_point`'s own `z` component (`z = sphere_radius *
    cos(gamma_b) * cos(u)`, and `z / sphere_radius = cos(colatitude)` by
    definition of colatitude) - kept as its own function since
    `spherical_involute_roll_angle_at_colatitude` (this function's
    inverse) and the flank-sampling range below both need it."""
    if not (0 < base_cone_half_angle < math.pi / 2):
        raise GearGeometryError(f"base_cone_half_angle must be in (0, pi/2), got {base_cone_half_angle!r}")
    u = math.sin(base_cone_half_angle) * roll_angle
    return math.acos(max(-1.0, min(1.0, math.cos(base_cone_half_angle) * math.cos(u))))


def spherical_involute_roll_angle_at_colatitude(base_cone_half_angle: float, colatitude: float) -> float:
    """Inverse of `spherical_involute_colatitude` - the spherical
    analogue of `gear_math.involute_roll_angle_at_radius`. `colatitude`
    must be at or outside the base cone (`colatitude >= base_cone_half_
    angle`) - like the planar involute, the spherical involute is only
    defined outside its own base circle (the generating great circle
    hasn't started rolling away from it yet at smaller colatitude)."""
    if colatitude < base_cone_half_angle:
        raise GearGeometryError(
            f"colatitude {colatitude!r} is inside the base cone (half-angle {base_cone_half_angle!r}) - "
            "not reachable by the spherical involute"
        )
    cos_gamma_b = math.cos(base_cone_half_angle)
    ratio = math.cos(colatitude) / cos_gamma_b
    u = math.acos(max(-1.0, min(1.0, ratio)))
    return u / math.sin(base_cone_half_angle)


def spherical_involute_azimuth_at_colatitude(base_cone_half_angle: float, colatitude: float) -> float:
    """The involute point's own azimuth (radians, around the cone axis)
    at a given `colatitude`, relative to the curve's `roll_angle = 0`
    start direction - the spherical analogue of
    `gear_math.involute_function` (`inv(alpha) = tan(alpha) - alpha`, the
    planar involute's own angular sweep from base-circle start to a given
    pressure angle), used the same way: placing a flank relative to its
    tooth's centerline (`gear_math._flank_start_offset_angle`'s spherical
    counterpart, see `_spherical_flank_start_offset_angle` below).

    Computed by evaluating `spherical_involute_point` at the `roll_angle`
    that reaches `colatitude` (via `spherical_involute_roll_angle_at_
    colatitude`) and reading off `atan2(y, x)` - not via a closed-form
    "spherical involute function" formula, because the point-evaluation
    route is simpler and no less rigorous, *and* because it leaves a
    genuinely independent closed form available for `test_bevel_math.py`
    to check this against: Napier's rule on the right spherical triangle
    `(pole N, tangency point B(theta), involute point P)` (right angle at
    `B`, legs `u = sin(gamma_b)*theta` opposite `N` and `gamma_b` opposite
    `P`, hypotenuse `colatitude` opposite the right angle) gives `sin(a) =
    sin(c) sin(A)` -> `sin(delta_phi) = sin(u) / sin(colatitude)` for the
    angle `delta_phi` at `N` between meridians to `B` and to `P`; the
    involute point *lags* the tangency point's own azimuth by this amount
    (`spherical_involute_point`'s `Tang(theta)` direction is the
    *decreasing*-theta tangent, matching `gear_math.involute_point`'s own
    handedness - see that function's docstring), so the involute's own
    azimuth is `theta - delta_phi`, not `theta + delta_phi`. A second,
    independently-derived formula for the same quantity
    (`test_bevel_math.py`'s `test_spherical_involute_azimuth_matches_
    independent_napier_rule_derivation`), not simply this function
    compared to itself."""
    roll_angle = spherical_involute_roll_angle_at_colatitude(base_cone_half_angle, colatitude)
    x, y, _z = spherical_involute_point(base_cone_half_angle, roll_angle)
    return math.atan2(y, x)


def sample_spherical_involute_flank(
    base_cone_half_angle: float,
    start_colatitude: float,
    end_colatitude: float,
    sphere_radius: float,
    point_count: int = 12,
) -> list[tuple[float, float, float]]:
    """Evenly-spaced-by-roll-angle sample of one spherical involute flank
    between `start_colatitude` and `end_colatitude`, on the sphere of
    radius `sphere_radius` centred at the cone apex (order preserved, like
    `gear_math.sample_involute_flank`) - the pure-Python "sample a
    spherical involute curve on a cone" prototype
    `docs/gear-design/10-bevel-gear.md` calls for. Call once with
    `sphere_radius = cone_distance` (outer/back cone) and once with
    `sphere_radius = cone_distance - face_width` (inner cone) to get the
    two space curves one flank's OCCT surface needs
    (`bevel_tooth_flank_pair` does exactly this for a full tooth)."""
    if point_count < 2:
        raise GearGeometryError(f"point_count must be >= 2, got {point_count!r}")
    t_start = spherical_involute_roll_angle_at_colatitude(base_cone_half_angle, start_colatitude)
    t_end = spherical_involute_roll_angle_at_colatitude(base_cone_half_angle, end_colatitude)
    return [
        spherical_involute_point(base_cone_half_angle, t_start + (t_end - t_start) * i / (point_count - 1), sphere_radius)
        for i in range(point_count)
    ]


