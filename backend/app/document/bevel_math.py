@dataclass
class BevelGearGeometry:
    """Fully-resolved dimensions for one straight bevel gear, derived from
    module/tooth-count/shaft-angle/pressure-angle - the bevel analogue of
    `gear_math.SpurGearGeometry`. All linear dimensions in mm, measured at
    the outer (large, back-cone) end, matching how bevel gear module is
    conventionally specified; all angles in radians unless named
    `*_degrees`."""

    module: float
    tooth_count: int
    mate_tooth_count: int | None
    pressure_angle: float
    shaft_angle: float
    backlash: float
    profile_shift: float
    pitch_cone_angle: float
    pitch_radius: float
    cone_distance: float
    face_width: float
    inner_cone_distance: float
    base_cone_angle: float
    addendum: float
    dedendum: float
    addendum_angle: float
    dedendum_angle: float
    face_cone_angle: float
    root_cone_angle: float
    tooth_thickness_at_pitch: float


def bevel_gear_geometry(
    *,
    module: float,
    tooth_count: int,
    mate_tooth_count: int | None = None,
    face_width: float,
    pressure_angle_degrees: float = 20.0,
    shaft_angle_degrees: float = 90.0,
    backlash: float = 0.0,
    profile_shift: float = 0.0,
    addendum_coefficient: float = 1.0,
    dedendum_coefficient: float = 1.25,
    pitch_cone_angle_degrees: float | None = None,
) -> BevelGearGeometry:
    """Resolve one straight bevel gear's cone geometry from its generative
    parameters, mirroring `gear_math.spur_gear_geometry`'s shape as
    closely as a genuinely different tooth-flank geometry allows. Per
    `docs/gear-design/10-bevel-gear.md`, `pitch_cone_angle` is a **direct
    input** for a real `BevelGearFeature` (a standalone bevel gear doesn't
    know a future meshing partner's tooth count on its own - `11-bevel-
    pair.md`'s pairing system computes it automatically) - pass
    `pitch_cone_angle_degrees` directly for that case, which skips
    `mate_tooth_count`/`shaft_angle_degrees`-based derivation entirely
    (both become unused; `mate_tooth_count` may be omitted, and
    `BevelGearGeometry.mate_tooth_count` is `None` on the result). Omitting
    `pitch_cone_angle_degrees` (the default, `None`) keeps this spike's own
    original behaviour: `mate_tooth_count` (required in that case) +
    `shaft_angle_degrees` derive the angle via `pitch_cone_half_angles`,
    since the spike this module started as needed to exercise that formula
    directly, not just take its own output as a given.

    `addendum`/`dedendum` use the same coefficients-times-module
    convention as `gear_math.spur_gear_geometry` (`addendum_coefficient`/
    `dedendum_coefficient` default to the same 1.0/1.25 full-depth values)
    applied at the outer (large) end - the standard "equal addendum"
    bevel system, not AGMA's Gleason long-and-short-addendum system (out
    of scope for this spike, per `10-bevel-gear.md`'s "straight bevel
    only" framing)."""
    if module <= 0:
        raise GearGeometryError(f"module must be positive, got {module!r}")
    if face_width <= 0:
        raise GearGeometryError(f"face_width must be positive, got {face_width!r}")
    if not (0 < pressure_angle_degrees < 90):
        raise GearGeometryError(f"pressure_angle_degrees must be in (0, 90), got {pressure_angle_degrees!r}")
    if backlash < 0:
        raise GearGeometryError(f"backlash must be >= 0, got {backlash!r}")

    pressure_angle = math.radians(pressure_angle_degrees)
    if pitch_cone_angle_degrees is not None:
        # <= 90 (not < ): 90 exactly is a crown gear (flat pitch cone) - see
        # `base_cone_half_angle`'s own identical boundary and docstring.
        # `root_cone_angle <= 0`/`face_width >= cone_distance` below still
        # catch any combination that's actually degenerate.
        if not (0 < pitch_cone_angle_degrees <= 90):
            raise GearGeometryError(
                f"pitch_cone_angle_degrees must be in (0, 90], got {pitch_cone_angle_degrees!r}"
            )
        pitch_cone_angle = math.radians(pitch_cone_angle_degrees)
    else:
        if mate_tooth_count is None:
            raise GearGeometryError("mate_tooth_count is required when pitch_cone_angle_degrees is not given")
        pitch_cone_angle, _mate_pitch_cone_angle = pitch_cone_half_angles(
            tooth_count, mate_tooth_count, shaft_angle_degrees
        )
    shaft_angle = math.radians(shaft_angle_degrees)

    pitch_radius = module * tooth_count / 2
    cone_distance = pitch_radius / math.sin(pitch_cone_angle)
    if face_width >= cone_distance:
        raise GearGeometryError(
            f"face_width ({face_width!r}) must be less than the cone distance ({cone_distance!r}) - "
            "a tooth can't run all the way to the apex"
        )
    inner_cone_distance = cone_distance - face_width

    base_cone_angle = base_cone_half_angle(pitch_cone_angle, pressure_angle)

    addendum = module * (addendum_coefficient + profile_shift)
    dedendum = module * (dedendum_coefficient - profile_shift)
    addendum_angle = math.atan(addendum / cone_distance)
    dedendum_angle = math.atan(dedendum / cone_distance)
    face_cone_angle = pitch_cone_angle + addendum_angle
    root_cone_angle = pitch_cone_angle - dedendum_angle
    if root_cone_angle <= 0:
        raise GearGeometryError(
            f"root_cone_angle {root_cone_angle!r} is non-positive - module {module!r}/tooth_count "
            f"{tooth_count!r}/profile_shift {profile_shift!r} don't form a valid bevel gear"
        )

    circular_pitch = math.pi * module
    tooth_thickness_at_pitch = (
        circular_pitch / 2 + 2 * profile_shift * module * math.tan(pressure_angle) - backlash
    )
    if tooth_thickness_at_pitch <= 0:
        raise GearGeometryError(
            f"tooth_thickness_at_pitch {tooth_thickness_at_pitch!r} is non-positive - "
            f"backlash {backlash!r} is too large for module {module!r}"
        )
    angular_tooth_thickness = tooth_thickness_at_pitch / pitch_radius
    if angular_tooth_thickness >= 2 * math.pi / tooth_count:
        raise GearGeometryError(
            "tooth_thickness_at_pitch exceeds the space available per tooth - "
            f"tooth_count {tooth_count!r} is too low for module {module!r}/profile_shift {profile_shift!r}"
        )

    return BevelGearGeometry(
        module=module,
        tooth_count=tooth_count,
        mate_tooth_count=mate_tooth_count,
        pressure_angle=pressure_angle,
        shaft_angle=shaft_angle,
        backlash=backlash,
        profile_shift=profile_shift,
        pitch_cone_angle=pitch_cone_angle,
        pitch_radius=pitch_radius,
        cone_distance=cone_distance,
        face_width=face_width,
        inner_cone_distance=inner_cone_distance,
        base_cone_angle=base_cone_angle,
        addendum=addendum,
        dedendum=dedendum,
        addendum_angle=addendum_angle,
        dedendum_angle=dedendum_angle,
        face_cone_angle=face_cone_angle,
        root_cone_angle=root_cone_angle,
        tooth_thickness_at_pitch=tooth_thickness_at_pitch,
    )


def max_recommended_face_width(cone_distance: float) -> float:
    """Standard rule-of-thumb face-width bound: `F <= cone_distance / 3`
    (a bevel tooth thins toward the apex, so too large a face width
    relative to cone distance runs the small end of the tooth toward
    degeneracy) - per `00-conventions.md`'s non-blocking-warning
    convention, callers should surface exceeding this as a warning
    banner, not reject creation outright (a wide-face bevel gear is still
    geometrically valid, just a worse design)."""
    if cone_distance <= 0:
        raise GearGeometryError(f"cone_distance must be positive, got {cone_distance!r}")
    return cone_distance / 3


# Rule-of-thumb pitch-cone-angle bound beyond which this app's simple
# solid-hub construction (`app.document.bevel._assemble_gear_solid` builds
# right out from the shared apex, with no separate hub/web/bore modeling)
# tends to leave too little material around a shaft bore to be structurally
# sound - not invalid geometry (a near-flat "crown gear" close to 90 degrees
# is a real, manufactured bevel gear form - confirmed on-device that `bevel_
# gear_geometry`/`bevel_tooth_flank_pair` stay perfectly well-behaved
# arbitrarily close to 90 degrees, no asymptote), just a case where the user
# likely needs to add their own backing material (e.g. a plate behind a
# crown-like gear) rather than relying on this app's default hub. Same
# non-blocking-warning convention as `max_recommended_face_width` above.
#
# On-device feedback (CI, real pythonocc-core): this constant used to also
# have a `NEEDLE_LIKE_PITCH_CONE_ANGLE_DEGREES = 15.0` low-end counterpart,
# warning near 0 degrees the same way - dropped entirely, not just retuned.
# This project's own canonical bevel gear test fixtures
# (`tests/test_bevel_gear_feature.py`'s `_PITCH_ANGLE_6_80` = 4.29 degrees,
# `_PITCH_ANGLE_18_90` = 11.3 degrees - real 6-tooth/18-tooth pinions mating
# with an 80-/90-tooth gear, high but entirely ordinary tooth-count ratios)
# sit well inside what a 15-degree threshold flagged, and those tests assert
# `warnings == []` deliberately - a small pinion's own pitch cone getting
# acute as its mate's tooth count grows is normal geometry, not a thin-hub
# risk the way a *wide, flat* crown gear genuinely is; the asymmetry (crown
# risk real, needle risk not) makes sense in hindsight - a small gamma
# still leaves the tooth's own full radial depth as hub material near the
# apex, nothing like a flat disc's shallow axial profile.
CROWN_LIKE_PITCH_CONE_ANGLE_DEGREES = 75.0


def thin_hub_warning(pitch_cone_angle_degrees: float) -> str | None:
    """`None` if `pitch_cone_angle_degrees` is comfortably within the
    "normal" bevel gear range, otherwise a warning string explaining why
    this gear's own hub/bore material may end up too thin - callers append
    this to their own `warnings` list exactly like `max_recommended_face_
    width`'s own comparison, non-blocking."""
    if pitch_cone_angle_degrees >= CROWN_LIKE_PITCH_CONE_ANGLE_DEGREES:
        return (
            f"pitch cone angle ({pitch_cone_angle_degrees!r}°) is close to (or at) 90° - this gear is "
            "wide and shallow like a flat 'crown' gear, so a shaft bore cut into it may leave too little "
            "material around the bore to be structurally sound. You may need to add your own backing "
            "material (e.g. a plate behind the gear) for a functioning part."
        )
    return None


