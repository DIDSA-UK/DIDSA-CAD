"""Pure-Python straight-bevel-gear geometry - no OCCT dependency, mirroring
`gear_math.py`'s own OCCT-free/OCCT-dependent module split
(`docs/gear-design/00-conventions.md`). This is a **spike/prototype**
module (`docs/gear-design/10-bevel-gear.md`'s own "budget real spike time"
instruction) - it resolves pitch-cone geometry and samples the spherical
involute tooth flank curve, but does not implement the full
`BevelGearFeature` six-part checklist (no dataclass Feature, no router, no
OCCT construction - see `app.document.bevel` for that, once/if this spike
is promoted to a real workstream).

**Why this is a genuinely different curve from `gear_math.py`'s planar
involute**: a spur/helical gear tooth flank is the involute of a circle -
generated by unwrapping a taut string (a straight line) from a base
*circle* in a plane. A bevel gear tooth flank is the involute of a cone -
generated by rolling a plane, without slipping, on a base *cone* whose
apex is the sphere's centre; the trace of a fixed point on that rolling
plane, confined to the sphere of a given radius (the "generating sphere"),
is the spherical involute. The rolling plane's intersection with the
generating sphere is a great circle (the spherical analogue of the
straight "string" line - both are geodesics of their respective surface),
and the base cone's intersection with the sphere is the base *circle* the
great circle rolls on - so this really is "roll a great circle without
slipping on a small circle, both living on a sphere," the direct spherical
analogue of `gear_math.involute_point`'s planar construction.

**Reference-value testing**: unlike `gear_math.py` (checked against
textbook spur gear tables), there is no existing precedent in this
codebase for spherical involute gearing, and no single well-known "textbook
example" this spike could find gives full-precision (x, y, z) points to
check against directly (see `docs/gear-design/10-bevel-gear.md`'s spike
findings). `backend/tests/test_bevel_math.py` instead leans on two
independently-checkable things: (1) the pitch-cone half-angle formula's own
stated Σ=90° reduction (`γ1 = atan(N1/N2)`), checked against exact
closed-form trig values (e.g. `atan(0.5)`, `atan(1/√3)`) that are
independently verifiable by hand/calculator, not derived from this module;
(2) the spherical involute curve's own azimuthal sweep, cross-checked
against a *second, independently-derived* closed form for the same
quantity built from Napier's rules for right spherical triangles (a
different derivation path through the same geometry - see
`spherical_involute_point`'s docstring), not merely re-deriving the same
formula and comparing it to itself.
"""

