# ---------------------------------------------------------------------------
# Pitch cone half-angles
# ---------------------------------------------------------------------------


def pitch_cone_half_angles(
    tooth_count_1: int, tooth_count_2: int, shaft_angle_degrees: float = 90.0
) -> tuple[float, float]:
    """The two mating gears' pitch cone half-angles (radians, `(gamma_1,
    gamma_2)`) for an arbitrary shaft angle `Sigma`, per
    `docs/gear-design/10-bevel-gear.md`: `gamma_1 = atan(sin(Sigma) /
    (N2/N1 + cos(Sigma)))`, `gamma_2 = Sigma - gamma_1`. At the common
    `Sigma = 90 deg` case this reduces to the textbook `gamma_1 =
    atan(N1/N2)` (`cos(90deg) = 0`, `sin(90deg) = 1`, so the general
    formula collapses to `atan(1 / (N2/N1)) = atan(N1/N2)`) - the
    known-value case `test_bevel_math.py` checks first, before trusting
    the general form for other shaft angles."""
    if tooth_count_1 < 4 or tooth_count_2 < 4:
        raise GearGeometryError("both tooth counts must be >= 4 to form a gear")
    if not (0 < shaft_angle_degrees < 180):
        raise GearGeometryError(f"shaft_angle_degrees must be in (0, 180), got {shaft_angle_degrees!r}")
    shaft_angle = math.radians(shaft_angle_degrees)
    gamma_1 = math.atan(math.sin(shaft_angle) / (tooth_count_2 / tooth_count_1 + math.cos(shaft_angle)))
    gamma_2 = shaft_angle - gamma_1
    if not (0 < gamma_1 < shaft_angle):
        raise GearGeometryError(
            f"tooth_count_1 {tooth_count_1!r}/tooth_count_2 {tooth_count_2!r}/shaft_angle_degrees "
            f"{shaft_angle_degrees!r} don't yield a valid pitch cone split"
        )
    return gamma_1, gamma_2


def base_cone_half_angle(pitch_cone_half_angle: float, pressure_angle: float) -> float:
    """The base cone half-angle `gamma_b` a spherical involute flank rolls
    off of, given this gear's own pitch cone half-angle `gamma` and the
    pressure angle `alpha` - the spherical analogue of
    `gear_math.spur_gear_geometry`'s `base_radius = pitch_radius *
    cos(pressure_angle)`.

    Derivation (Napier's rules for a right spherical triangle): let `N` be
    the cone apex/axis pole, `p0` the pitch point (on the pitch circle,
    colatitude `gamma`), and `T` the point where the spherical involute's
    generating great circle (the "line of action" great circle through
    `p0`, tangent to the base circle) touches the base circle. `T` is the
    foot of the perpendicular arc from `N` to that great circle, so arc
    `N-T = gamma_b` by definition of the base cone; the triangle `N, T,
    p0` has a right angle at `T`. The tangent to the pitch circle at `p0`
    is perpendicular to the meridian arc `N-p0`, and the line of action
    meets it at the pressure angle `alpha`, so the triangle's angle at
    `p0` (between meridian `N-p0` and side `p0-T`) is `90deg - alpha`.
    Napier's rule `sin(leg) = sin(hypotenuse) * sin(opposite angle)` with
    hypotenuse `N-p0 = gamma` and the leg `N-T = gamma_b` opposite that
    `90deg - alpha` angle gives `sin(gamma_b) = sin(gamma) * sin(90deg -
    alpha) = sin(gamma) * cos(alpha)` - the planar `cos(pressure_angle)`
    factor, carried through a sine instead of applied directly, because
    `gamma`/`gamma_b` are *angles* on the sphere where the planar
    construction has *radii*.

    Degenerate-but-independently-checkable cases (used directly as
    reference values in `test_bevel_math.py`, not just "it runs"):
    `alpha = 0` collapses this to `gamma_b = gamma` (`cos(0) = 1`, base
    cone coincides with the pitch cone, matching the planar
    `base_radius = pitch_radius` at zero pressure angle); `gamma = 90deg`
    (a crown gear) gives `gamma_b = 90deg - alpha` exactly (`sin(gamma_b) =
    cos(alpha) = sin(90deg - alpha)`)."""
    # <= pi/2 (not < ): pi/2 exactly is a real, manufactured crown gear (this
    # function's own docstring above already calls out "gamma = 90deg (a
    # crown gear) gives gamma_b = 90deg - alpha exactly" as a reference
    # case) - confirmed on-device this stays perfectly finite at the
    # boundary, no asymptote (sin(gamma_b) = cos(alpha), never zero/undefined
    # for a valid pressure_angle).
    if not (0 < pitch_cone_half_angle <= math.pi / 2):
        raise GearGeometryError(f"pitch_cone_half_angle must be in (0, pi/2], got {pitch_cone_half_angle!r}")
    if not (0 <= pressure_angle < math.pi / 2):
        raise GearGeometryError(f"pressure_angle must be in [0, pi/2), got {pressure_angle!r}")
    return math.asin(math.sin(pitch_cone_half_angle) * math.cos(pressure_angle))


